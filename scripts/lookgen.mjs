// Generates the wiki looks. Seeds are random and stay in memory: only the resulting colours and
// typeface are written. Usage: node lookgen.mjs [out.js]   (default ./looks.js)
//
// Writes window.WIKI_LOOKS = [house, A, B]: 0 is the fixed house look (Inter, for the lessons
// site), 1 a light look and 2 a dark one. Every text colour is at least 7:1 (WCAG AAA) on every
// surface it can sit on (paper, panel, raise, sel); control borders (`line`) at least 3:1; the
// accent never carries text and is kept out of the purple band.
import { randomBytes } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { oklchToHex, contrast } from './lookgen-lib.mjs';

// Text-capable families only (spec §6), with their Fontsource ids for self-hosting.
export const FAMILIES = [
  { f: 'Geist', id: 'geist' },
  { f: 'Inter', id: 'inter' },
  { f: 'IBM Plex Sans', id: 'ibm-plex-sans' },
  { f: 'Hanken Grotesk', id: 'hanken-grotesk' },
  { f: 'Space Grotesk', id: 'space-grotesk' },
];
const AAA = 7, UI = 3, TRIES = 5;

const HOUSE = { dark: false, f: "'Inter'", font: 'inter', v: { paper: '#F5F4F0', panel: '#FFFFFF', raise: '#FFFFFF', ink: '#151515', body: '#272626', mute: '#4C4B48', rule: '#E2E0DA', line: '#8B8985', acc: '#1F5C99', sel: '#EAE8E2' } };

const fnv = (s) => { let h = 2166136261; for (const c of s) { h ^= c.charCodeAt(0); h = Math.imul(h, 16777619); } return h >>> 0; };
const rng = (a) => () => { a |= 0; a = (a + 0x6d2b79f5) | 0; let t = Math.imul(a ^ (a >>> 15), 1 | a); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
const purple = (h) => h > 250 || h < 20;

/** The colour closest to the surfaces (by OKLCH L) that still reaches `min` on all of them. */
function solve(surfaces, min, C, H, from, to) {
  const step = from < to ? 0.005 : -0.005;
  let best = null;
  for (let L = from; step > 0 ? L <= to : L >= to; L += step) {
    const hex = oklchToHex(L, C, H);
    if (surfaces.every((s) => contrast(hex, s) >= min)) best = hex; else break;
  }
  return best;
}

function make(seed, dark) {
  const r = rng(fnv(seed));
  let hue = Math.round(r() * 360);
  if (hue > 250 && hue < 340) hue = (hue + 120) % 360;
  let ah = (hue + 100 + Math.round(r() * 160)) % 360;
  while (purple(ah)) ah = (ah + 47) % 360;
  const fam = FAMILIES[Math.floor(r() * FAMILIES.length)];
  const o = (L, C, H = hue) => oklchToHex(L, C, H);
  const v = dark
    ? { paper: o(0.165, 0.008), panel: o(0.19, 0.01), raise: o(0.215, 0.01), sel: o(0.24, 0.012), ink: o(0.94, 0.008), rule: o(0.28, 0.012), acc: o(0.8, 0.14, ah) }
    : { paper: o(0.972, 0.012), panel: o(0.993, 0.004), raise: '#FFFFFF', sel: o(0.935, 0.012), ink: o(0.19, 0.012), rule: o(0.9, 0.014), acc: o(0.52, 0.17, ah) };
  const surf = [v.paper, v.panel, v.raise, v.sel];
  // Walk from the ink towards the paper and stop at the last colour that still passes.
  v.mute = solve(surf, AAA + 0.1, 0.012, hue, dark ? 0.94 : 0.19, dark ? 0.5 : 0.7);
  v.body = v.mute && oklchToHex(dark ? 0.86 : 0.3, 0.01, hue);
  v.line = solve(surf.slice(0, 3), UI + 0.1, 0.012, hue, dark ? 0.94 : 0.19, dark ? 0.3 : 0.85);
  const gates = {
    ink: Math.min(...surf.map((s) => contrast(v.ink, s))),
    body: v.body ? Math.min(...surf.map((s) => contrast(v.body, s))) : 0,
    mute: v.mute ? Math.min(...surf.map((s) => contrast(v.mute, s))) : 0,
    line: v.line ? Math.min(...surf.slice(0, 3).map((s) => contrast(v.line, s))) : 0,
    accMark: contrast(v.acc, v.paper),
  };
  const ok = gates.ink >= AAA && gates.body >= AAA && gates.mute >= AAA && gates.line >= UI && gates.accMark >= UI;
  return { ok, look: { dark, f: `'${fam.f}'`, font: fam.id, v }, gates };
}

/** One look per mode; after TRIES failed seeds, the house palette (dark variant for dark). */
function pick(dark, avoid) {
  for (let i = 0; i < TRIES; i++) {
    const t = make(randomBytes(48).toString('base64url'), dark);
    if (t.ok && !(avoid && avoid.font === t.look.font)) return t;
  }
  return { ok: false, look: dark ? { ...HOUSE, dark: true, v: { paper: '#141413', panel: '#1A1A19', raise: '#222220', sel: '#272725', ink: '#F0EFEA', body: '#DAD9D4', mute: '#B3B2AD', rule: '#2C2C2A', line: '#6E6D69', acc: '#4FB3E6' } } : HOUSE, gates: {} };
}

const A = pick(false);
const B = pick(true, A.look);
const looks = [HOUSE, A.look, B.look];
const out = process.argv[2] || 'looks.js';
writeFileSync(out, `// Generated by wiki-this/scripts/lookgen.mjs. Colours and faces only; no seed is stored.\nwindow.WIKI_LOOKS = ${JSON.stringify(looks, null, 1)};\n`);
for (const [n, t] of [['A', A], ['B', B]]) {
  const g = Object.entries(t.gates).map(([k, x]) => `${k} ${x.toFixed(2)}`).join(', ');
  console.log(`${n}: ${t.look.dark ? 'dark' : 'light'} ${t.look.f} ${t.ok ? g : 'fallback palette'}`);
}
